/// Предупреждение браузера при закрытии вкладки.
///
/// Нужен ровно для одного: пока на экране показан секрет токена, который
/// человек ещё не скопировал, закрытие вкладки теряет его безвозвратно
/// (`docs/design/screens/tokens.md`).
///
/// **Это подстраховка, а не защита.** Браузер показывает собственный текст,
/// свой показать нельзя, а без взаимодействия со страницей диалога может
/// не быть вовсе. Основная защита — подтверждение внутри приложения; оно
/// работает всегда и не зависит от политики браузера.
///
/// Спрятан за интерфейсом, потому что веб-специфика не должна протекать
/// в экраны: на мобильном клиенте вкладок нет.
abstract interface class UnloadGuard {
  /// Просит браузер переспросить перед закрытием вкладки.
  /// Повторный вызов ничего не меняет.
  void arm();

  /// Снимает предупреждение. Вызывать обязательно: иначе оно переживёт
  /// экран и будет спрашивать на пустом месте.
  void disarm();
}

/// Платформенная реализация [UnloadGuard].
///
/// Подменяется в тестах: проверять надо намерение защитить секрет,
/// а не то, что тестовый рендерер умеет закрывать вкладки.
final unloadGuardProvider = Provider<UnloadGuard>(
  (ref) => impl.createUnloadGuard(),
);
