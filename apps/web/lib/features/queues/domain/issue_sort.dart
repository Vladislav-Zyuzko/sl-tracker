import 'package:sl_tracker_web/core/api/generated/export.dart';

/// Порядок задач в списке очереди (US-32, D-28).
///
/// Вариантов ровно два, и они живут в явном выпадающем списке, а не в кликах
/// по заголовкам колонок: заголовок, который выглядит кликабельным, но
/// не сортирует, хуже статичного.
///
/// Своё перечисление, а не сгенерированный `Sort`: имя `Sort` в контракте
/// получилось из имени query-параметра и ничего не говорит о том, что
/// сортируется. Заодно интерфейс не зависит от того, как генератор назовёт
/// параметр в следующий раз.
enum IssueSort {
  /// Приоритет по убыванию, при равенстве номер по убыванию. По умолчанию.
  priority('priority', 'По приоритету'),

  /// Только по номеру по убыванию: «Сначала новые».
  newest('newest', 'Сначала новые');

  /// @nodoc
  const IssueSort(this.code, this.label);

  /// Значение query-параметра `sort` — оно же попадает в адрес страницы.
  final String code;

  /// Подпись в выпадающем списке.
  final String label;

  /// Значение по умолчанию: в адресе оно не пишется.
  static const initial = IssueSort.priority;

  /// Разбирает значение из адреса страницы.
  ///
  /// Незнакомое значение — это не ошибка, а опечатка в скопированной ссылке:
  /// падать из-за неё нельзя, показываем порядок по умолчанию.
  static IssueSort parse(String? code) {
    for (final sort in values) {
      if (sort.code == code) return sort;
    }

    return initial;
  }

  /// Значение для сгенерированного клиента.
  Sort get dto => switch (this) {
    IssueSort.priority => Sort.priority,
    IssueSort.newest => Sort.newest,
  };
}
