/// Состояние сессии пользователя.
///
/// Сессия живёт в httpOnly cookie: клиент её не читает и токенов не хранит
/// (ADR-0001). Всё, что известно фронту, — ответил ли сервер на `GET /api/me`.
enum SessionState {
  /// Ещё не проверяли: приложение только что запустилось.
  ///
  /// Роутер в этом состоянии никуда не уводит и показывает загрузку —
  /// иначе при перезагрузке страницы пользователя выкидывало бы на вход
  /// каждый раз, пока идёт проверка.
  unknown,

  /// Проверка идёт.
  checking,

  /// Пользователь внутри.
  authenticated,

  /// Сессии нет — обычный вход.
  anonymous,

  /// Сессия была и истекла: пользователю показывается модалка «Войдите снова»,
  /// а несохранённый текст остаётся в локальном черновике (US-02).
  expired,
}
