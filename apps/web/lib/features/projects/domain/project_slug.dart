/// Короткое имя проекта в адресе (`/projects/<slug>`, ADR-0005, D-35).
///
/// Правила повторяют серверные (`apps/api/src/projects/project-slug.ts`)
/// и нужны ровно для двух вещей:
///
/// 1. предпросмотр адреса в форме создания проекта — «Адрес проекта будет:»;
/// 2. приведение ввода к допустимому виду на лету в настройках (US-18):
///    человек печатает «Сладкий Лимит», в поле появляется `sladkiy-limit`.
///
/// **Окончательное значение всегда выдаёт сервер.** Коллизию с уже занятым
/// именем клиент увидеть не может: при ней сервер добавит суффикс (`-2`),
/// и предпросмотр разойдётся с итогом. Поэтому подпись — «будет», а не
/// «адрес проекта», а после ответа показывается поле `slug` из ответа.
sealed class ProjectSlug {
  /// Длина ограничена 40 символами (D-35).
  static const maxLength = 40;

  /// Разрешённый вид: строчные латинские буквы, цифры и одиночные дефисы
  /// внутри.
  static final pattern = RegExp(r'^[a-z0-9]+(?:-[a-z0-9]+)*$');

  /// Системные адреса приложения: проект с таким коротким именем перекрыл бы
  /// собственный маршрут клиента. Список повторяет серверный — расхождение
  /// означало бы, что клиент разрешает ввод, который сервер отвергнет.
  static const reserved = <String>{
    'access-denied',
    'api',
    'invite',
    'issues',
    'login',
    'me',
    'notifications',
    'profile',
    'projects',
    'queues',
  };

  /// Таблица транслитерации кириллицы.
  ///
  /// Проверочный пример из D-35: «Сладкий Лимит 2026!» → `sladkiy-limit-2026`.
  /// Мягкий и твёрдый знаки пропадают, а не становятся апострофом.
  static const _cyrillic = <String, String>{
    'а': 'a',
    'б': 'b',
    'в': 'v',
    'г': 'g',
    'д': 'd',
    'е': 'e',
    'ё': 'e',
    'ж': 'zh',
    'з': 'z',
    'и': 'i',
    'й': 'y',
    'к': 'k',
    'л': 'l',
    'м': 'm',
    'н': 'n',
    'о': 'o',
    'п': 'p',
    'р': 'r',
    'с': 's',
    'т': 't',
    'у': 'u',
    'ф': 'f',
    'х': 'h',
    'ц': 'ts',
    'ч': 'ch',
    'ш': 'sh',
    'щ': 'sch',
    'ъ': '',
    'ы': 'y',
    'ь': '',
    'э': 'e',
    'ю': 'yu',
    'я': 'ya',
  };

  /// Латиница с диакритикой.
  ///
  /// Сервер снимает диакритику нормализацией NFKD, которой в `dart:core` нет.
  /// Вместо подключения пакета ради предпросмотра — короткая таблица частых
  /// букв: она закрывает европейские названия и не тянет в бандл ничего.
  /// Буква не из таблицы станет дефисом, и предпросмотр разойдётся
  /// с серверным именем — расхождение безобидно и снимается ответом сервера.
  static const _latinFolding = <String, String>{
    'á': 'a',
    'à': 'a',
    'â': 'a',
    'ä': 'a',
    'ã': 'a',
    'å': 'a',
    'ā': 'a',
    'æ': 'ae',
    'ç': 'c',
    'č': 'c',
    'ć': 'c',
    'ď': 'd',
    'đ': 'd',
    'é': 'e',
    'è': 'e',
    'ê': 'e',
    'ë': 'e',
    'ě': 'e',
    'ē': 'e',
    'í': 'i',
    'ì': 'i',
    'î': 'i',
    'ï': 'i',
    'ī': 'i',
    'ł': 'l',
    'ñ': 'n',
    'ň': 'n',
    'ń': 'n',
    'ó': 'o',
    'ò': 'o',
    'ô': 'o',
    'ö': 'o',
    'õ': 'o',
    'ø': 'o',
    'ō': 'o',
    'œ': 'oe',
    'ř': 'r',
    'š': 's',
    'ś': 's',
    'ş': 's',
    'ß': 'ss',
    'ť': 't',
    'ú': 'u',
    'ù': 'u',
    'û': 'u',
    'ü': 'u',
    'ū': 'u',
    'ů': 'u',
    'ý': 'y',
    'ÿ': 'y',
    'ž': 'z',
    'ź': 'z',
    'ż': 'z',
  };

  /// Кириллица латиницей, посимвольно. Остальные буквы проходят как есть.
  static String transliterate(String value) {
    final result = StringBuffer();

    // Посимвольно по кодовым единицам: суррогатные половины эмодзи в таблицы
    // не попадают и всё равно станут дефисом, как и на сервере.
    for (final char in value.toLowerCase().split('')) {
      result.write(_cyrillic[char] ?? _latinFolding[char] ?? char);
    }

    return result.toString();
  }

  /// Короткое имя из названия проекта.
  ///
  /// Пустая строка означает «из названия не вышло ни одного допустимого
  /// символа» (название из эмодзи): сервер в этом случае выдаст `project-<n>`,
  /// и предсказать номер клиент не может.
  static String slugify(String name) {
    final cleaned = transliterate(name)
        .replaceAll(RegExp('[^a-z0-9]+'), '-')
        .replaceAll(RegExp('-+'), '-')
        .replaceAll(RegExp(r'^-|-$'), '');

    return _trimToLength(cleaned, maxLength);
  }

  /// Приводит ввод к допустимому виду **на лету** (US-18).
  ///
  /// От [slugify] отличается одним: хвостовой дефис сохраняется, пока человек
  /// печатает. Иначе «сладкий-» превращалось бы в «сладкий», и следующая
  /// буква прилипала бы к предыдущему слову.
  static String normalizeInput(String value) {
    final cleaned = transliterate(value)
        .replaceAll(RegExp('[^a-z0-9]+'), '-')
        .replaceAll(RegExp('-+'), '-')
        .replaceAll(RegExp('^-'), '');

    return cleaned.length <= maxLength
        ? cleaned
        : cleaned.substring(0, maxLength);
  }

  /// Почему сервер откажет в таком имени. `null` — имя годится.
  ///
  /// Коды совпадают с серверными (`invalid_slug`, `reserved_slug`): экран
  /// показывает один и тот же текст, ответил ли сервер или проверил клиент.
  static String? validate(String raw) {
    final value = raw.trim();

    if (value.isEmpty || value.length > maxLength || !pattern.hasMatch(value)) {
      return 'invalid_slug';
    }

    return reserved.contains(value) ? 'reserved_slug' : null;
  }

  /// Обрезка по длине без висящего дефиса на конце.
  static String _trimToLength(String value, int max) {
    if (value.length <= max) return value;

    return value.substring(0, max < 1 ? 1 : max).replaceAll(RegExp('-+\$'), '');
  }
}
